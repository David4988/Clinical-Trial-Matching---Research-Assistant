def test_eligible_patient_flows_all_the_way_to_a_next_dose_decision(rig):
    """ELIGIBLE -> treatment -> observations -> state -> risk -> intervention -> next dose."""
    screening, treatment = _register_eligible(rig)
    patient_id = treatment.patient_id

    trial_id = treatment.trial_id
    batch = generate_windowed(
        patient_id, trial_id, Trajectory.STABLE, START, windows=1, hours=4, seed=5
    )[0]
    now = max(o.recorded_at for o in batch)
    ingestion = rig["ingestion"].ingest(batch, now=now)
    assert ingestion.accepted_count > 0

    cycle = rig["monitoring"].run_cycle(patient_id, trial_id, now)

    # 1. Patient state was built from the ingested observations.
    assert cycle.state.observation_count == ingestion.accepted_count
    assert cycle.state.treatment.treatment_id == treatment.treatment_id
    assert cycle.state.measurements

    # 2. Risk was generated by the provider.
    assert cycle.risk.provider == "mock-risk-v1"
    assert cycle.risk.level is RiskLevel.GREEN

    # 3. The trust gate ran and let the verdict through.
    assert cycle.effective_risk.level is RiskLevel.GREEN
    assert cycle.effective_risk.gated is False

    # 4. An intervention came from the protocol table.
    assert cycle.interventions
    assert cycle.interventions[0].protocol_rule_id.startswith("DEMO-")

    # 5. A next-dose decision was reached.
    assert cycle.next_dose is not None
    assert cycle.next_dose.decision is NextDoseDecision.PROCEED
    assert cycle.next_dose.decision_support_only is True

    # 6. It all persisted together.
    stored = rig["repo"].get_cycle(cycle.cycle_id)
    assert stored is not None
    assert stored.next_dose.decision is NextDoseDecision.PROCEED
    assert stored.state.patient_id == patient_id


