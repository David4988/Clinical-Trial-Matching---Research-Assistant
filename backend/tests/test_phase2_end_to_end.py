# Trial ids come from the fixtures, never hardcoded here: patient_eligible is
# screened against trial_supported (CT-002), while the PDF demo record uses
# trial_demo (CT-001). Every helper below takes the trial id from the treatment
# that was actually registered.
START = datetime(2026, 8, 16, 6, 0, tzinfo=timezone.utc)


@pytest.fixture
def rig(tmp_path):
    screening_repo = JsonRepository(tmp_path / "store.json")
    monitoring_repo = JsonMonitoringRepository(tmp_path / "monitoring.json")
    return {
        "screening": ScreeningService(repository=screening_repo),
        "treatment": TreatmentService(screening_repo, monitoring_repo),
        "ingestion": ObservationIngestionService(monitoring_repo),
        "monitoring": MonitoringService(monitoring_repo),
        "repo": monitoring_repo,
    }


def _register_eligible(rig):
    """Phase 1 screening through to a registered Phase 2 treatment."""
    screening = rig["screening"].screen(
        load_patient("patient_eligible"), load_trial("trial_supported")
    )
    assert screening.overall_status is OverallStatus.ELIGIBLE

    treatment = rig["treatment"].register(
        screening_result_id=screening.result_id,
        drug_name="Compound X",
        now=START,
    )
    return screening, treatment


def _drive(rig, treatment, trajectory, windows=5, seed=7):
    """Ingest a trajectory window by window, running a cycle after each."""
    patient_id, trial_id = treatment.patient_id, treatment.trial_id
    batches = generate_windowed(
        patient_id, trial_id, trajectory, START, windows=windows, hours=8, seed=seed
    )
    cycles = []
    for batch in batches:
        now = max(o.recorded_at for o in batch)
        rig["ingestion"].ingest(batch, now=now)
        cycles.append(rig["monitoring"].run_cycle(patient_id, trial_id, now))
    return cycles


def _collapse(levels):
    out = []
    for level in levels:
        if not out or out[-1] is not level:
            out.append(level)
    return out


