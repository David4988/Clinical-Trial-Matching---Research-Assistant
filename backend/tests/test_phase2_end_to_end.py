def test_phase_one_screening_is_unaffected_by_phase_two(rig):
    """Phase 2 activity must not disturb Phase 1 behaviour."""
    before = rig["screening"].screen(
        load_patient("patient_pdf_demo"), load_trial("trial_demo")
    )

    _, treatment = _register_eligible(rig)
    _drive(rig, treatment, Trajectory.GRADUAL_DETERIORATION)

    after = rig["screening"].screen(
        load_patient("patient_pdf_demo"), load_trial("trial_demo")
    )

    assert before.overall_status is after.overall_status
    assert before.rule_coverage == after.rule_coverage
    assert [r.status for r in before.criteria_results] == [
        r.status for r in after.criteria_results
    ]
    assert len(before.disagreements) == len(after.disagreements)
