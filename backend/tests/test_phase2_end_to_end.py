"""M9/M12: the Phase 2 vertical slice, end to end.

The critical integration test proves the whole chain on real components — no
stubs beyond the deterministic risk provider that Phase 2 actually ships:

    ELIGIBLE screening
      -> treatment registered
      -> observations ingested
      -> patient state updated
      -> risk generated
      -> trust gate applied
      -> intervention generated
      -> next-dose decision generated

and that Phase 1 still behaves identically alongside it.
"""

