def test_the_timeline_records_the_whole_story_in_order(rig):
    _, treatment = _register_eligible(rig)
    rig["treatment"].record_dose(treatment.treatment_id, 5, "mg", now=START)

    _drive(rig, treatment, Trajectory.GRADUAL_DETERIORATION)

    events = rig["repo"].list_events(treatment.patient_id)
    types = [e.event_type for e in events]

    for expected in (
        MonitoringEventType.TREATMENT_REGISTERED,
        MonitoringEventType.DOSE_ADMINISTERED,
        MonitoringEventType.OBSERVATIONS_INGESTED,
        MonitoringEventType.RISK_ASSESSED,
        MonitoringEventType.RISK_TRANSITION,
        MonitoringEventType.INTERVENTION_RAISED,
        MonitoringEventType.NOTIFICATION_CREATED,
        MonitoringEventType.NEXT_DOSE_ASSESSED,
    ):
        assert expected in types, f"{expected.value} missing from the timeline"

    stamps = [e.occurred_at for e in events]
    assert stamps == sorted(stamps)


def test_every_decision_retains_its_inputs(rig):
    """A decision and the evidence for it are stored as one object."""
    _, treatment = _register_eligible(rig)
    cycles = _drive(rig, treatment, Trajectory.GRADUAL_DETERIORATION)
    final = cycles[-1]

    assert final.risk.contributing_factors
    assert all(i.evidence for i in final.interventions)
    assert final.next_dose.criteria
    assert final.next_dose.reasons
    assert final.state.measurements


def test_transitions_are_recorded_between_cycles(rig):
    _, treatment = _register_eligible(rig)
    cycles = _drive(rig, treatment, Trajectory.GRADUAL_DETERIORATION)

    transitions = [c.transition for c in cycles if c.transition]

    assert transitions[0].from_level is None  # first assessment
    assert any(
        t.from_level is RiskLevel.GREEN and t.to_level is RiskLevel.AMBER
        for t in transitions
    )


def test_repeat_cycles_without_new_data_report_no_transition(rig):
    _, treatment = _register_eligible(rig)
    batch = generate_windowed(
        treatment.patient_id, treatment.trial_id, Trajectory.STABLE, START,
        windows=1, hours=4, seed=5
    )[0]
    now = max(o.recorded_at for o in batch)
    rig["ingestion"].ingest(batch, now=now)

    first = rig["monitoring"].run_cycle(treatment.patient_id, treatment.trial_id, now)
    second = rig["monitoring"].run_cycle(treatment.patient_id, treatment.trial_id, now)

    assert first.transition is not None  # first ever assessment
    assert second.transition is None  # nothing changed


