def test_deterioration_escalates_and_holds_the_next_dose(rig):
    _, treatment = _register_eligible(rig)

    cycles = _drive(rig, treatment, Trajectory.GRADUAL_DETERIORATION)
    levels = _collapse([c.effective_risk.level for c in cycles])

    assert levels == [RiskLevel.GREEN, RiskLevel.AMBER, RiskLevel.RED]

    def interval(cycle):
        return next(
            i.monitoring_interval_minutes
            for i in cycle.interventions
            if i.monitoring_interval_minutes is not None
        )

    # Monitoring intensity increased along the way.
    assert interval(cycles[-1]) < interval(cycles[0])

    # A clinician was alerted, and the dose is held.
    assert any(
        i.action is InterventionAction.URGENT_ESCALATION
        for i in cycles[-1].interventions
    )
    assert cycles[-1].notifications
    assert cycles[-1].next_dose.decision is NextDoseDecision.HOLD


def test_recovery_de_escalates_and_returns_to_proceed(rig):
    _, treatment = _register_eligible(rig)

    cycles = _drive(rig, treatment, Trajectory.RECOVERY)
    levels = _collapse([c.effective_risk.level for c in cycles])

    assert levels == [RiskLevel.RED, RiskLevel.AMBER, RiskLevel.GREEN]
    assert cycles[0].next_dose.decision is NextDoseDecision.HOLD
    assert cycles[-1].next_dose.decision is NextDoseDecision.PROCEED


def test_failing_sensor_produces_unknown_not_a_reassuring_green(rig):
    """The trust gate's whole reason for existing."""
    _, treatment = _register_eligible(rig)

    cycles = _drive(rig, treatment, Trajectory.NOISY_SENSOR)
    final = cycles[-1]

    assert final.effective_risk.level is RiskLevel.UNKNOWN
    assert final.effective_risk.gated is True
    # The model's own opinion is retained, not erased.
    assert final.effective_risk.provider_level is RiskLevel.GREEN
    # And UNKNOWN demands more attention, not less.
    assert any(
        i.action is InterventionAction.REQUEST_REPEAT_OBSERVATION
        for i in final.interventions
    )
    assert final.next_dose.decision is not NextDoseDecision.PROCEED


